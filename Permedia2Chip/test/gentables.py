import hunk
s,h=hunk.parse('bin/p2_717.chip'); c=h[0]['data']; d=h[1]['data']
T=[('DPMSValues','ULONG',c,0x1a0,4),('DACValues','UBYTE',c,0x1b0,24),
   ('DstFormat','UBYTE',c,0xd98,24),('TextureFormat','UBYTE',c,0xdb0,24),('DepthMask','UBYTE',c,0xdc8,12),
   ('ReadPixelValues','UBYTE',c,0xdd4,24),('MinTerms','UBYTE',c,0xdec,16),('EnginePartProd','UWORD',c,0xdfc,65),
   ('Numerators','UBYTE',c,0x29a4,669),('Denominators','UBYTE',c,0x2c42,669),('PixelClocks','ULONG',c,0x2ee0,669),
   ('NibbleZoom','UBYTE',c,0x3c28,16),('PixelWidth','UWORD',d,4,22)]
sz={'UBYTE':1,'UWORD':2,'ULONG':4}
o=['/* tables taken unchanged from 3DLabsPermedia2.chip 7.17 (generated by gentables.py) */','#include <exec/types.h>','']
for n,t,b,off,cnt in T:
    k=sz[t]; v=[int.from_bytes(b[off+i*k:off+i*k+k],'big') for i in range(cnt)]
    f='0x%02x' if k==1 else ('0x%04x' if k==2 else '%d' if n=='PixelClocks' else '0x%08x')
    per=16 if k==1 else (12 if k==2 else 8)
    o.append('const %s %s[%d] = {'%(t,n,cnt))
    for i in range(0,cnt,per): o.append('\t'+', '.join(f%x for x in v[i:i+per])+',')
    o.append('};\n')
open('src/tables.c','w').write('\n'.join(o))
